/**
 * Replaces dynamic placeholders like {name}, {clinic_name}, etc., in a template string.
 */
export function interpolatePlaceholders(text = '', data = {}) {
  if (!text) return ''
  return text.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => {
    if (data[key] !== undefined && data[key] !== null) {
      return data[key]
    }
    // Formatted fallback for empty/missing placeholders
    return match
  })
}

/**
 * Builds a clean, professional, mobile-responsive HTML email document.
 */
export function buildHtmlEmail({
  title = 'ClinicOS Notification',
  preheader = '',
  recipientName = 'Valued User',
  subject = '',
  headline = '',
  bodyText = '',
  details = [], // Array of { label, value }
  actionUrl = '',
  actionText = '',
  clinicName = 'ClinicOS Healthcare SaaS',
  supportEmail = 'support@clinicos.health',
  footerNote = 'You received this automated notification because of your registered ClinicOS account activity.',
}) {
  const detailsHtml = details && details.length > 0
    ? `
      <table style="width: 100%; border-collapse: collapse; margin: 20px 0; background-color: #f8fafc; border-radius: 8px; border: 1px solid #e2e8f0;">
        <tbody>
          ${details
            .map(
              (item, i) => `
            <tr style="border-bottom: ${i === details.length - 1 ? 'none' : '1px solid #edf2f7'};">
              <td style="padding: 10px 14px; font-size: 12px; color: #64748b; font-weight: 600; width: 38%;">${item.label}</td>
              <td style="padding: 10px 14px; font-size: 13px; color: #1e293b; font-weight: 700;">${item.value}</td>
            </tr>
          `
            )
            .join('')}
        </tbody>
      </table>
    `
    : ''

  const ctaButtonHtml = actionUrl && actionText
    ? `
      <div style="text-align: center; margin: 28px 0 20px;">
        <a href="${actionUrl}" style="background-color: #2563eb; color: #ffffff; padding: 12px 28px; text-decoration: none; border-radius: 8px; font-weight: 700; font-size: 13px; display: inline-block; box-shadow: 0 2px 4px rgba(37,99,235,0.2);">
          ${actionText} &rarr;
        </a>
      </div>
    `
    : ''

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${subject || title}</title>
  <style>
    body { margin: 0; padding: 0; background-color: #f1f5f9; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; -webkit-font-smoothing: antialiased; }
    .email-container { max-width: 600px; margin: 30px auto; background-color: #ffffff; border-radius: 12px; overflow: hidden; border: 1px solid #e2e8f0; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.05); }
    .header-bar { background: linear-gradient(135deg, #1e3a8a 0%, #2563eb 100%); padding: 24px; text-align: left; }
    .brand-pill { display: inline-flex; align-items: center; background-color: rgba(255,255,255,0.15); border: 1px solid rgba(255,255,255,0.25); border-radius: 9999px; padding: 4px 12px; color: #ffffff; font-size: 11px; font-weight: 700; letter-spacing: 0.05em; text-transform: uppercase; }
    .content-body { padding: 32px 28px; color: #334155; line-height: 1.6; font-size: 14px; }
    .greeting { font-size: 17px; font-weight: 700; color: #0f172a; margin-bottom: 12px; }
    .headline { font-size: 20px; font-weight: 800; color: #0f172a; margin: 0 0 14px; line-height: 1.3; }
    .footer { background-color: #f8fafc; border-top: 1px solid #e2e8f0; padding: 20px 28px; font-size: 11px; color: #94a3b8; text-align: center; }
    @media only screen and (max-width: 600px) {
      .email-container { width: 100% !important; margin: 0 !important; border-radius: 0 !important; }
      .content-body { padding: 24px 18px !important; }
    }
  </style>
</head>
<body>
  ${preheader ? `<div style="display:none;font-size:1px;color:#333;line-height:1px;max-height:0px;max-width:0px;opacity:0;overflow:hidden;">${preheader}</div>` : ''}
  <table role="presentation" width="100%" cellspacing="0" cellpadding="0" style="background-color: #f1f5f9; padding: 20px 0;">
    <tr>
      <td align="center">
        <div class="email-container">
          <!-- Header -->
          <div class="header-bar">
            <div class="brand-pill">ClinicOS Healthcare SaaS</div>
            <div style="color: #ffffff; font-size: 22px; font-weight: 800; margin-top: 10px; letter-spacing: -0.02em;">
              ${clinicName || 'ClinicOS Platform'}
            </div>
          </div>

          <!-- Body -->
          <div class="content-body">
            <div class="greeting">Hello ${recipientName || 'Valued User'},</div>
            ${headline ? `<div class="headline">${headline}</div>` : ''}
            <div style="color: #475569; font-size: 13.5px; margin-bottom: 16px; white-space: pre-line;">
              ${bodyText}
            </div>

            ${detailsHtml}

            ${ctaButtonHtml}

            <div style="margin-top: 28px; padding-top: 16px; border-top: 1px solid #f1f5f9; font-size: 11.5px; color: #64748b;">
              <strong>Need assistance?</strong> Contact our support desk at <a href="mailto:${supportEmail}" style="color: #2563eb; text-decoration: none;">${supportEmail}</a> or reply directly to this message.
            </div>
          </div>

          <!-- Footer -->
          <div class="footer">
            <div style="margin-bottom: 6px; font-weight: 600; color: #64748b;">${clinicName} &bull; Powered by ClinicOS Healthcare Suite</div>
            <div>${footerNote}</div>
            <div style="margin-top: 8px; color: #cbd5e1;">&copy; 2026 ClinicOS Inc. All medical rights and confidential records reserved.</div>
          </div>
        </div>
      </td>
    </tr>
  </table>
</body>
</html>`
}

